import { Registry, Cache } from '../../src/structures/index.js'

describe('Cache', () => {
  let cache
  beforeEach(() => {
    cache = new Cache()
  })
  it('is a registry named cache by default, unbounded and without expiration', () => {
    expect(cache).toBeInstanceOf(Registry)
    expect(cache.name).toBe('cache')
    expect(cache.max).toBe(Infinity)
    expect(cache.ttl).toBe(0)
  })
  it('rejects an invalid max', () => {
    for (const max of [0, -1, 1.5, NaN, -Infinity, '2', null]) {
      expect(() => new Cache('cache', { max })).toThrow('max must be a positive integer or Infinity')
    }
  })
  it('rejects an invalid ttl', () => {
    for (const ttl of [-1, 1.5, NaN, Infinity, '100', null]) {
      expect(() => new Cache('cache', { ttl })).toThrow('ttl must be a non-negative integer')
    }
  })
  it('rejects unsafe or mistyped limits in production', async () => {
    vi.stubEnv('NODE_ENV', 'production')
    vi.resetModules()
    try {
      const { Cache } = await import('../../src/structures/cache.js')
      expect(() => new Cache('cache', { max: -1 })).toThrow('max must be a positive integer or Infinity')
      expect(() => new Cache('cache', { ttl: '100' })).toThrow('ttl must be a non-negative integer')
    } finally {
      vi.unstubAllEnvs()
      vi.resetModules()
    }
  })
  it('sets a new entry and replaces an existing one', () => {
    expect(cache.set('osm', 1)).toBe(1)
    expect(cache.set('osm', 2)).toBe(2)
    expect(cache.get('osm')).toBe(2)
    expect(cache.size).toBe(1)
  })
  it('replaces an existing entry through replace()', () => {
    cache.set('osm', 1)
    expect(cache.replace('osm', 2)).toBe(2)
    expect(cache.get('osm')).toBe(2)
    expect(cache.size).toBe(1)
  })
  it('rejects replacement of an unknown entry', () => {
    expect(() => cache.replace('unknown', 1)).toThrow('[cache] entry not registered: unknown')
    expect(cache.size).toBe(0)
  })
  it('preserves the previous value when replace() receives nil', () => {
    cache.set('osm', 1)
    expect(() => cache.replace('osm', undefined)).toThrow('value must be defined')
    expect(() => cache.replace('osm', null)).toThrow('value must be defined')
    expect(cache.get('osm')).toBe(1)
  })
  it('keeps the registry contract: register() still rejects duplicates', () => {
    cache.register('osm', 1)
    expect(() => cache.register('osm', 2)).toThrow('[cache] entry already registered: osm')
    expect(cache.get('osm')).toBe(1)
  })
  it('keeps the previous value when set() is given a nil value', () => {
    cache.set('osm', 1)
    expect(() => cache.set('osm', undefined)).toThrow('value must be defined')
    expect(() => cache.set('osm', null)).toThrow('value must be defined')
    expect(cache.get('osm')).toBe(1)
  })
  it('rejects an invalid key', () => {
    expect(() => cache.set('', 1)).toThrow('key must be a non-empty string')
    expect(() => cache.replace('', 1)).toThrow('key must be a non-empty string')
    expect(() => cache.get('')).toThrow('key must be a non-empty string')
    expect(() => cache.has('')).toThrow('key must be a non-empty string')
    expect(cache.size).toBe(0)
  })
  it('returns undefined for an unknown key', () => {
    expect(cache.get('unknown')).toBeUndefined()
    expect(cache.has('unknown')).toBe(false)
  })
  it('computes a missing entry once with getOrSet()', () => {
    const compute = vi.fn((key) => ({ key }))
    const first = cache.getOrSet('osm', compute)
    expect(cache.getOrSet('osm', compute)).toBe(first)
    expect(first).toEqual({ key: 'osm' })
    expect(compute).toHaveBeenCalledOnce()
  })
  it('shares an in-flight computation', async () => {
    const compute = vi.fn(async () => 42)
    const first = cache.getOrSet('a', compute)
    const second = cache.getOrSet('a', compute)
    expect(second).toBe(first)
    expect(await first).toBe(42)
    expect(compute).toHaveBeenCalledOnce()
  })
  it('stores nothing when compute throws', () => {
    expect(() => cache.getOrSet('osm', () => { throw new Error('boom') })).toThrow('boom')
    expect(cache.has('osm')).toBe(false)
  })
  it('rejects a compute that is not a function or that returns nil', () => {
    expect(() => cache.getOrSet('osm', 1)).toThrow('compute must be a function')
    expect(() => cache.getOrSet('osm', () => undefined)).toThrow('value must be defined')
    expect(cache.has('osm')).toBe(false)
  })
  it('clears all entries', () => {
    cache.set('a', 1)
    cache.set('b', 2)
    cache.clear()
    expect(cache.size).toBe(0)
    expect(cache.entries()).toEqual([])
  })
  describe('with max', () => {
    beforeEach(() => {
      cache = new Cache('cache', { max: 2 })
    })
    it('evicts the least recently used entry when full', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['b', 'c'])
    })
    it('evicts when full through register() too', () => {
      cache.register('a', 1)
      cache.register('b', 2)
      cache.register('c', 3)
      expect(cache.keys()).toEqual(['b', 'c'])
    })
    it('refreshes recency on get()', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      cache.get('a')
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['a', 'c'])
    })
    it('does not change recency on a cache miss', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      expect(cache.get('unknown')).toBeUndefined()
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['b', 'c'])
    })
    it('refreshes recency on set() of an existing key', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      cache.set('a', 3)
      cache.set('c', 4)
      expect(cache.entries()).toEqual([['a', 3], ['c', 4]])
    })
    it('refreshes recency when replacing an entry', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      expect(cache.replace('a', 3)).toBe(3)
      cache.set('c', 4)
      expect(cache.entries()).toEqual([['a', 3], ['c', 4]])
    })
    it('refreshes recency on a getOrSet() hit', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      cache.getOrSet('a', () => 0)
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['a', 'c'])
    })
    it('does not refresh recency on has(), keys(), values() or entries()', () => {
      cache.set('a', 1)
      cache.set('b', 2)
      cache.has('a')
      cache.keys()
      cache.values()
      cache.entries()
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['b', 'c'])
    })
  })
  describe('with ttl', () => {
    beforeEach(() => {
      vi.useFakeTimers()
      cache = new Cache('cache', { ttl: 100 })
    })
    afterEach(() => {
      vi.useRealTimers()
    })
    it('keeps an entry until its ttl elapses', () => {
      cache.set('osm', 1)
      vi.advanceTimersByTime(99)
      expect(cache.get('osm')).toBe(1)
      vi.advanceTimersByTime(1)
      expect(cache.has('osm')).toBe(false)
      expect(cache.get('osm')).toBeUndefined()
    })
    it('prunes expired entries from size, keys(), values() and entries()', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(50)
      cache.set('b', 2)
      vi.advanceTimersByTime(50)
      expect(cache.size).toBe(1)
      expect(cache.keys()).toEqual(['b'])
      expect(cache.values()).toEqual([2])
      expect(cache.entries()).toEqual([['b', 2]])
    })
    it('purges unrelated expired entries on writes to an unbounded cache', () => {
      const unregister = vi.spyOn(cache, 'unregister')
      cache.set('old', 1)
      vi.advanceTimersByTime(50)
      cache.set('live', 2)
      vi.advanceTimersByTime(50)
      cache.set('new', 3)
      expect(unregister.mock.calls).toEqual([['old']])
      expect(cache.entries()).toEqual([['live', 2], ['new', 3]])
    })
    it('purges expired entries behind live entries after a clock rollback', () => {
      const unregister = vi.spyOn(cache, 'unregister')
      vi.setSystemTime(1000)
      cache.set('live', 1)
      vi.setSystemTime(950)
      cache.set('old', 2)
      vi.setSystemTime(1050)
      cache.set('new', 3)
      expect(unregister.mock.calls).toEqual([['old']])
      expect(cache.entries()).toEqual([['live', 1], ['new', 3]])
    })
    it('does not refresh the ttl on get()', () => {
      cache.set('osm', 1)
      vi.advanceTimersByTime(60)
      cache.get('osm')
      vi.advanceTimersByTime(40)
      expect(cache.has('osm')).toBe(false)
    })
    it('refreshes the ttl on set()', () => {
      cache.set('osm', 1)
      vi.advanceTimersByTime(60)
      cache.set('osm', 2)
      vi.advanceTimersByTime(60)
      expect(cache.get('osm')).toBe(2)
    })
    it('refreshes the ttl when replacing an entry', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(60)
      cache.replace('a', 2)
      vi.advanceTimersByTime(60)
      expect(cache.get('a')).toBe(2)
      vi.advanceTimersByTime(40)
      expect(cache.has('a')).toBe(false)
    })
    it('rejects replacement of an expired entry', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(100)
      expect(() => cache.replace('a', 2)).toThrow('[cache] entry not registered: a')
      expect(cache.has('a')).toBe(false)
      expect(cache.size).toBe(0)
    })
    it('recomputes an expired entry with getOrSet()', () => {
      const compute = vi.fn(() => 1)
      cache.getOrSet('osm', compute)
      vi.advanceTimersByTime(100)
      cache.getOrSet('osm', compute)
      expect(compute).toHaveBeenCalledTimes(2)
    })
    it('accepts register() on an expired key', () => {
      cache.register('osm', 1)
      vi.advanceTimersByTime(100)
      expect(() => cache.register('osm', 2)).not.toThrow()
      expect(cache.get('osm')).toBe(2)
    })
    it('removes expiration metadata on unregister()', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(60)
      cache.unregister('a')
      cache.set('a', 2)
      vi.advanceTimersByTime(50)
      expect(cache.get('a')).toBe(2)
    })
    it('removes expiration metadata on clear()', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(60)
      cache.clear()
      cache.set('a', 2)
      vi.advanceTimersByTime(50)
      expect(cache.get('a')).toBe(2)
    })
  })
  describe('with max and ttl', () => {
    beforeEach(() => {
      vi.useFakeTimers()
      cache = new Cache('cache', { max: 2, ttl: 100 })
    })
    afterEach(() => {
      vi.useRealTimers()
    })
    it('drops expired entries before evicting a live one', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(90)
      cache.set('b', 2)
      vi.advanceTimersByTime(5)
      cache.get('a')
      vi.advanceTimersByTime(55)
      cache.set('c', 3)
      expect(cache.keys()).toEqual(['b', 'c'])
    })
    it('refreshes recency and ttl when replacing an entry', () => {
      cache.set('a', 1)
      vi.advanceTimersByTime(50)
      cache.set('b', 2)
      vi.advanceTimersByTime(25)
      cache.replace('a', 3)
      vi.advanceTimersByTime(50)
      cache.set('c', 4)
      expect(cache.entries()).toEqual([['a', 3], ['c', 4]])
    })
  })
})
